// Package keymap translates between macOS virtual keycodes, USB HID usage codes
// (the wire format) and Windows set-1 scancodes. All mappings are positional, so
// the receiving machine's keyboard layout decides which character is produced.
package keymap

// HID usage codes for modifiers (used by the client for Cmd/Ctrl swapping).
const (
	HIDLeftCtrl   = 0xE0
	HIDLeftShift  = 0xE1
	HIDLeftAlt    = 0xE2
	HIDLeftGUI    = 0xE3
	HIDRightCtrl  = 0xE4
	HIDRightShift = 0xE5
	HIDRightAlt   = 0xE6
	HIDRightGUI   = 0xE7
	HIDCapsLock   = 0x39
	HIDMute       = 0x7F
	HIDVolUp      = 0x80
	HIDVolDown    = 0x81
)

